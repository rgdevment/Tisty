/** Says a word in the language asked, with `{name}` filled when it carries one. */
export type Say = (word: Word, name?: string) => string;

export const sayIn = (locale: string): Say => {
  const words: Record<Word, string> = locale.toLowerCase().startsWith("es") ? ES : EN;
  return (word, name) => words[word].replace(/\{name\}/g, () => name ?? "");
};
