export type Words = {
  readonly locale: string;
  readonly say: (word: Own, name?: string) => string;
  readonly sayToSheet: Say;
};

const filled = (text: string, name = "", other = ""): string =>
  text.replaceAll("{name}", () => name).replaceAll("{other}", () => other);

export const wordsFor = (asked: string | null): Words => {
  const spanish = asked === "es";
  const own = spanish ? ES : EN;
  const sheet = spanish ? SHEET_ES : SHEET_EN;
  return {
    locale: spanish ? "es" : "en",
    say: (word, name) => filled(own[word], name),
    sayToSheet: (word, ...named) => filled(sheet[word], named[0], named[1]),
  };
};
